"""
The real test: MapNet vs strong baselines on a real document set.

    python -m realtest.run                         # Kubernetes docs + 40 hand-written questions
    python -m realtest.run --generate 60           # + 60 questions generated by your local model
    python -m realtest.run --corpus ~/my-docs --questions my-questions.json
    python -m realtest.run --retrieval-only        # skip answering (fast)

What it measures, for every contender:
  found      the file that answers the question is among the k passages retrieved
  rank       reciprocal rank of the first right passage (MRR)
  scanned    passages/nodes scored per question (work done)
  evidence   the passages handed to the model contain the answer (keyword check,
             hand-written questions only; needs no model)
  answered   the local model's answer is right (keyword check, or a judge model
             for generated questions)
  fresh      same, for questions whose files were added AFTER the indexes were
             built, plus how long each index took to absorb them

Results go to realtest/results/<timestamp>/report.md and results.json.
"""
