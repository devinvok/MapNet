def evaluate(items, retrievers, k, readers, answer_with, model_judge, timing=None):
    """Run ONE METHOD AT A TIME (all its questions, then the next method), so Ollama
    keeps the same model loaded instead of swapping between the embedding model and
    the map model on every question. Methods don't affect each other, so the results
    are the same. Then each reader answers the same passages, one reader at a time.

    `timing`, if given, is filled with wall-clock seconds: timing["retrieve"][method],
    timing["answer"][reader model]."""
    rows, pending = [], []
    timing = timing if timing is not None else {}
    ret_t, ans_t = timing.setdefault("retrieve", {}), timing.setdefault("answer", {})
    for mi, r in enumerate(retrievers, 1):
        t_method = time.perf_counter()
        for item in items:
            gold = set(item["files"])
            t0 = time.perf_counter()
            hits, scanned = r.search(item["q"], k)
            ms = (time.perf_counter() - t0) * 1000
            files = [f for f, _, _ in hits]
            rank = next((i + 1 for i, f in enumerate(files) if f in gold), None)
            row = dict(q=item["q"], retriever=r.name, found=rank is not None,
                       rr=1 / rank if rank else 0.0, scanned=scanned, ms=ms, files=files[:3],
                       generated=item.get("generated", False), fresh=item.get("fresh", False),
                       evidence=evidence(hits, item))
            if readers and r.name in answer_with:
                pending.append((row, item, hits))
            rows.append(row)
        secs = time.perf_counter() - t_method
        ret_t[r.name] = ret_t.get(r.name, 0.0) + secs
        log(f"    [{mi}/{len(retrievers)}] {r.name}: {len(items)} questions retrieved in {secs:.0f}s")
    for ri, reader in enumerate(readers or []):
        log(f"    answering {len(pending)} with {reader.model} ...")
        t_reader = time.perf_counter()
        for n, (row, item, hits) in enumerate(pending, 1):
            a = reader.answer(item["q"], [P(f"{f}#", t) for f, t, _ in hits])
            res = dict(answer=a.text, answer_s=a.seconds, tokens_in=a.input_tokens,
                       correct=judge(a.text, item, model_judge))
            row.setdefault("by_reader", {})[reader.model] = res
            if ri == 0:
                row.update(res)
            if n % 50 == 0:
                log(f"      {n}/{len(pending)} answered ({time.perf_counter() - t_reader:.0f}s so far)")
        secs = time.perf_counter() - t_reader
        ans_t[reader.model] = ans_t.get(reader.model, 0.0) + secs
        log(f"    {reader.model}: {len(pending)} answers in {secs:.0f}s")
    return rows


def evidence(hits, item):
    """Do the passages handed to the model contain the answer?"""
    if not item.get("expect"):
        return None
    text = "\n".join(t for _, t, _ in hits).lower()
    ok = all(re.search(p, text) for p in item["expect"])
    if item.get("expect_any"):
        ok = ok and any(re.search(p, text) for p in item["expect_any"])
    return ok


class HideCards:
    """Card store view that pretends some files were never carded (the
    freshness test: those files 'arrive' later and get cards on arrival)."""

    def __init__(self, store, hidden_texts):
        self.store, self.hidden = store, {content_key(t) for t in hidden_texts}

    def get(self, text):
        return None if content_key(text) in self.hidden else self.store.get(text)

    def get_file(self, text):
        return None if content_key(text) in self.hidden else self.store.get_file(text)


def summarize(rows, names):
    out = {}
    for name in names:
        rs = [r for r in rows if r["retriever"] == name]
        if not rs:
            continue
        judged = [r["correct"] for r in rs if r.get("correct") is not None]
        ev = [r["evidence"] for r in rs if r.get("evidence") is not None]
        out[name] = dict(
            n=len(rs), found=sum(r["found"] for r in rs) / len(rs),
            mrr=statistics.mean(r["rr"] for r in rs),
            scanned=statistics.mean(r["scanned"] for r in rs),
            ms=statistics.median(r["ms"] for r in rs),
            evidence=(sum(ev) / len(ev)) if ev else None,
            answered=(sum(judged) / len(judged)) if judged else None, n_judged=len(judged),
            tokens_in=statistics.mean([r["tokens_in"] for r in rs if "tokens_in" in r] or [0]),
            answer_s=statistics.mean([r["answer_s"] for r in rs if "answer_s" in r] or [0]))
        per, secs = {}, {}
        for r in rs:
            for model, res in r.get("by_reader", {}).items():
                secs.setdefault(model, []).append(res["answer_s"])
                if res["correct"] is not None:
                    per.setdefault(model, []).append(res["correct"])
        out[name]["by_reader"] = {m: (sum(v) / len(v), len(v)) for m, v in per.items()}
        # time: lookups include first-visit work (mapping/embedding) that the median hides
        out[name]["lookup_mean_s"] = statistics.mean(r["ms"] for r in rs) / 1000
        out[name]["lookup_total_s"] = sum(r["ms"] for r in rs) / 1000
        out[name]["lookup_max_s"] = max(r["ms"] for r in rs) / 1000
        out[name]["answer_mean_s"] = {m: statistics.mean(v) for m, v in secs.items()}
        out[name]["answer_total_s"] = {m: sum(v) for m, v in secs.items()}
    return out


def _dur(s):
    return f"{s:.1f}s" if s < 60 else f"{s / 60:.1f} min"


def time_table(summary, title):
    """Where the time goes, per method: the lookup (median, mean, slowest, total) and
    the reader's answer time. 'Per question' = mean lookup + mean answer, per reader."""
    models = list(dict.fromkeys(m for s in summary.values() for m in s.get("answer_mean_s", {})))
    cols = ["Lookup median", "Lookup mean", "Lookup slowest", "Lookup total"]
    for m in models:
        cols += [f"Answer ({m})", f"Per question ({m})", f"Total ({m})"]
    lines = [f"### {title}: time", "", "| Method | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for name, s in summary.items():
        cells = [f"{s['ms'] / 1000:.2f}s", f"{s['lookup_mean_s']:.2f}s",
                 f"{s['lookup_max_s']:.1f}s", _dur(s["lookup_total_s"])]
        for m in models:
            if m in s.get("answer_mean_s", {}):
                a = s["answer_mean_s"][m]
                cells += [f"{a:.1f}s", f"{s['lookup_mean_s'] + a:.1f}s",
                          _dur(s["lookup_total_s"] + s["answer_total_s"][m])]
            else:
                cells += ["n/a"] * 3
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def table(summary, title):
    models = list(dict.fromkeys(m for s in summary.values() for m in s.get("by_reader", {})))
    ans_cols = [f"Answer right ({m})" for m in models] if len(models) > 1 else ["Answer right"]
    lines = [f"### {title}", "",
             "| Method | Right file in top-k | MRR | Answer in passages | Scanned per question | "
             "Lookup (median) | " + " | ".join(ans_cols) + " |",
             "|---|---|---|---|---|---|" + "---|" * len(ans_cols)]
    for name, s in summary.items():
        ev = f"{s['evidence']:.0%}" if s["evidence"] is not None else "n/a"
        if len(models) > 1:
            ans = [f"{s['by_reader'][m][0]:.0%} ({s['by_reader'][m][1]})" if m in s["by_reader"] else "n/a"
                   for m in models]
        else:
            ans = [f"{s['answered']:.0%} ({s['n_judged']})" if s["answered"] is not None else "n/a"]
        lines.append(f"| {name} | {s['found']:.0%} ({s['n']}) | {s['mrr']:.2f} | {ev} | "
                     f"{s['scanned']:,.0f} | {s['ms']:.0f} ms | " + " | ".join(ans) + " |")
    return "\n".join(lines) + "\n"


def explain_report(rows, beam=6):
    """Markdown: for ref-map, was a miss the walk's fault or the references'? The control scores
    every reference directly (no walk) and takes the best `beam` files."""
    if not rows:
        return ""
    ok = lambda r, k="flat_rank": bool(r[k]) and r[k] <= beam  # noqa: E731
    both = [r for r in rows if r["in_chosen"] and ok(r)]
    walk_only = [r for r in rows if r["in_chosen"] and not ok(r)]
    lost = [r for r in rows if not r["in_chosen"] and ok(r)]
    neither = [r for r in rows if not r["in_chosen"] and not ok(r)]
    lines = ["## Why ref-map missed (hand-written questions)", "",
             f"The control scores the question against every reference directly, with no walk, and takes "
             f"the best {beam} files. If the control also misses, the references can't find the page; "
             f"if only the walk misses, the walk lost it. ('Found by the walk' means the right file was "
             f"among the files the walk picked to read, up to {beam}; the main table counts a file only if "
             f"one of the returned passages comes from it, so the two numbers can differ.)", "",
             "| | Questions |", "|---|---|",
             f"| Found by the walk and by the control | {len(both)} |",
             f"| Found by the walk only | {len(walk_only)} |",
             f"| **Control finds it, the walk lost it** | {len(lost)} |",
             f"| **Neither finds it (the references can't)** | {len(neither)} |", ""]
    if lost:
        far = sum(1 for r in lost if not r["home_visited"])
        cut = sum(1 for r in lost if r["cut"])
        lines += [f"Where the walk lost it ({len(lost)}): never entered the right folder: {far}; "
                  f"chosen but past the limit of new files read per question: {cut}; "
                  f"entered the folder but ranked it too low: {len(lost) - far - cut}.", ""]
    if neither:
        ranks = sorted(r["flat_rank"] or 10 ** 6 for r in neither)
        mid = ranks[len(ranks) // 2]
        lines += [f"Where the right file ranked in the control when nothing found it: median "
                  f"{'beyond the list' if mid >= 10 ** 6 else mid}.", ""]
    from collections import Counter
    mags = [(f, c) for f, c in Counter(r["flat_top"] for r in rows if not ok(r) and r["flat_top"]).most_common(6)
            if c >= 2]
    if mags:
        lines += ["Files that took first place for several questions they don't answer (magnets): "
                  + "; ".join(f"`{f}` ×{c}" for f, c in mags), ""]
    wt = [r for r in rows if "with_terms" in r]
    if wt:
        t_walk = sum(1 for r in wt if r["with_terms"]["in_chosen"])
        t_ctl = sum(1 for r in wt if r["with_terms"]["flat_rank"] and r["with_terms"]["flat_rank"] <= beam)
        lines += [f"With the question translated into technical terms: the walk finds the file for {t_walk} of "
                  f"{len(wt)} questions (without: {sum(r['in_chosen'] for r in wt)}); the control for {t_ctl} "
                  f"(without: {sum(ok(r) for r in wt)}).", "",
                  "What the translator wrote for the questions nothing found:", ""]
        for r in neither[:8]:
            lines.append(f"- “{r['q']}” → {r['with_terms']['terms'] or '(nothing)'}")
        lines.append("")
    gr = [r for r in rows if "graph" in r]
    if gr:
        line = (f"The graph walk (a navigable graph over the same references, no folders) finds the file for "
                f"{sum(r['graph']['in_chosen'] for r in gr)} of {len(gr)} questions; the folder walk finds "
                f"{sum(r['in_chosen'] for r in gr)}; the control {sum(ok(r) for r in gr)}.")
        if any("with_terms" in r["graph"] for r in gr):
            line += (f" With the question translated first: graph "
                     f"{sum(r['graph'].get('with_terms', {}).get('in_chosen', False) for r in gr)}, folder walk "
                     f"{sum(r.get('with_terms', {}).get('in_chosen', False) for r in gr)}.")
        lines += [line, ""]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--corpus", default="k8s", help="'k8s' or a folder path")
    ap.add_argument("--questions", help="question file (default for k8s: realtest/questions/k8s.json)")
    ap.add_argument("--generate", type=int, default=0, help="also generate N questions with the local model")
    ap.add_argument("--limit", type=int, help="use only the first N hand-written questions")
    ap.add_argument("--k", type=int, default=4, help="passages handed to the model")
    ap.add_argument("--model", help="default for both --reader-model and --map-model (qwen2.5:3b)")
    ap.add_argument("--reader-model", help="the READER: answers from the passages. Several, comma-separated, "
                    "to compare them on the same passages (e.g. qwen2.5:3b,qwen2.5:7b)")
    ap.add_argument("--map-model", help="the CARTOGRAPHER: writes file descriptions and section cards")
    ap.add_argument("--embed-model", help="the NAVIGATOR's embedding model, and embed-all's "
                    "(default nomic-embed-text)")
    ap.add_argument("--retrieval-only", action="store_true", help="don't generate answers")
    ap.add_argument("--only", help="use only these top-level folders, for every method "
                    "(e.g. concepts,tasks,tutorials,setup)")
    ap.add_argument("--cards", help="card store from `python -m mapnet.cards` (default: <data>/cards)")
    ap.add_argument("--no-lazy", action="store_true", help="skip the methods that map files on arrival")
    ap.add_argument("--skip", default="", help="comma-separated methods to leave out (saves time)")
    ap.add_argument("--explain", action="store_true",
                    help="after the questions: for ref-map, say why each miss happened (compares the "
                         "walk with scoring every reference directly)")
    ap.add_argument("--answer-with",
                    default="keyword-all,embed-all,map,map+sections,map+lazy-cards,map+file-cards,"
                            "map+meaning,map+cards,map+embed,embed-tree,ref-map,ref-map+terms,ref-graph,ref-graph+terms,"
                            "token-net,token-net+assoc,token-net+sections,page-mean,page-text,"
                            "token-net+page-mean,token-net+embed-all,token-prox,token-window,"
                            "token-prox+window,token-prox+window+page-mean,token-graph,token-graph+prox,token-graph+page-mean,"
                            "token-conv-window,token-conv-graph,token-conv-graph2",
                    help="which methods get their passages answered by the model")
    ap.add_argument("--data", default=str(HERE / "data"), help="where corpora and work copies live")
    args = ap.parse_args()

    t_start = time.perf_counter()
    skip_set = {x.strip() for x in args.skip.split(",") if x.strip()}
    data = Path(args.data)
    data.mkdir(parents=True, exist_ok=True)
    if args.corpus == "k8s":
        corpus = fetch_k8s(data, log)
        qfile = Path(args.questions or HERE / "questions" / "k8s.json")
    else:
        corpus = Path(args.corpus).expanduser().resolve()
        qfile = Path(args.questions) if args.questions else None
    items = json.loads(qfile.read_text(encoding="utf-8")) if qfile else []
    if args.limit:
        items = items[: args.limit]

    # ---- models
    # three roles: the navigator walks the map (words + a small embedding model, never
    # writes text), the cartographer writes the map, the reader answers from passages
    reader = OllamaReader(args.map_model or args.model)  # the cartographer
    have_reader = reader.available()
    reader_models = [m.strip() for m in (args.reader_model or args.model or "").split(",") if m.strip()] or [None]
    answer_models = [OllamaReader(m) for m in reader_models]
    emb = OllamaEmbedder(args.embed_model, cache_dir=str(data / ".cache"))
    if not emb.available():
        log(f"! Embedding model '{emb.model}' not found in Ollama; using a weak no-model stand-in.\n"
            f"  The embed-all numbers will NOT represent real embedding search. "
            f"Fix: ollama pull {emb.model}")
        emb = LsaEmbedder()
    if not have_reader:
        log(f"! Map model '{reader.model}' not found in Ollama: methods that write cards are skipped. "
            f"Fix: ollama pull {reader.model}")
    if args.retrieval_only:
        answer_readers = None
    else:
        answer_readers = [r for r in answer_models if r.available()]
        for r in answer_models:
            if not r.available():
                log(f"! Reader model '{r.model}' not found in Ollama; skipping it. Fix: ollama pull {r.model}")
        if not answer_readers:
            log("! No reader model available; answers use the no-model extractive fallback.")
            answer_readers = [ExtractiveReader()]

    # ---- working copy; hold out the files of 'fresh' questions
    work = data / "work" / corpus.name
    if work.exists():
        shutil.rmtree(work)
    if args.only:
        keep = [x.strip() for x in args.only.split(",") if x.strip()]
        for d in keep:
            shutil.copytree(corpus / d, work / d)
        before = len(items)
        items = [x for x in items if any(f.split("/")[0] in keep for f in x["files"])]
        items = [dict(x, files=[f for f in x["files"] if f.split("/")[0] in keep]) for x in items]
        log(f"Using only {', '.join(keep)}: {len(items)} of {before} questions have an answer there.")
    else:
        shutil.copytree(corpus, work)
    holdout_dir = data / "work" / f"{corpus.name}-holdout"
    if holdout_dir.exists():
        shutil.rmtree(holdout_dir)
    fresh_items = [x for x in items if x.get("fresh")]
    held = sorted({f for x in fresh_items for f in x["files"]})
    for f in held:
        if (work / f).exists():
            (holdout_dir / f).parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(work / f), str(holdout_dir / f))

    # ---- build
    log(f"\nBuilding indexes over {corpus} ...")
    shared = Shared(work)
    n_files, n_chunks = len(shared.map.sources()), shared.map.root.n_docs
    log(f"  map: {n_files:,} files, {n_chunks:,} passages in {shared.build_s:.1f}s")
    t0 = time.perf_counter()
    embed_all = EmbedAll(shared, emb, log)
    log(f"  embeddings ({emb.name}): {time.perf_counter() - t0:.1f}s")
    retrievers = [KeywordAll(shared), embed_all, MapRoute(shared),
                  MapRoute(shared, "map+sections", sections=True)]

    # agent-written cards, if they've been built (python -m mapnet.cards ...)
    store = CardStore(args.cards or data / "cards")
    held_texts = [read_file(holdout_dir / f) for f in held if (holdout_dir / f).exists()]
    card_info, shared_cards = None, None
    if store.count():
        shared_cards = Shared(work, cards=HideCards(store, held_texts))
        carded = sum(1 for s in shared_cards.map.sources() if s.cards)
        card_secs = sum((store.meta(read_file(work / s.path)) or {}).get("seconds", 0)
                        for s in shared_cards.map.sources() if s.cards)
        card_info = (carded, card_secs)
        log(f"  cards: {carded:,} of {n_files:,} files carded (built in {card_secs / 60:.0f} min of model time)")
        retrievers.append(MapRoute(shared_cards, "map+cards", sections=True))
    else:
        log(f"  cards: none found in {store.dir} (build them with: python -m mapnet.cards "
            f"{corpus} --store {store.dir})")
    lazy = None
    if have_reader and not args.no_lazy:
        lazy_dir = data / "work" / "lazy-cards"  # starts empty every run
        if lazy_dir.exists():
            shutil.rmtree(lazy_dir)
        lazy = MapLazy(Shared(work, cards=CardStore(lazy_dir)), CardStore(lazy_dir), reader)
        retrievers.append(lazy)
        log("  map+lazy-cards: starts with no cards; each file is mapped the first time a "
            "question reaches it")
    elif not have_reader:
        log("  map+lazy-cards: skipped (needs the reader model)")

    # the full chain: file descriptions built in advance + section maps on arrival
    file_info, chain = None, None
    if store.count_files() and have_reader and not args.no_lazy:
        chain_dir = data / "work" / "chain-cards"  # section cards start empty every run
        if chain_dir.exists():
            shutil.rmtree(chain_dir)
        combined = CombinedCards(HideCards(store, held_texts), CardStore(chain_dir))
        chain_shared = Shared(work, cards=combined)
        chain = MapLazy(chain_shared, combined, reader, name="map+file-cards", route_weight=0.3)
        described = [s for s in chain_shared.map.sources() if s.file_card]
        d_secs = sum((store.file_meta(read_file(work / s.path)) or {}).get("seconds", 0) for s in described)
        file_info = (len(described), d_secs)
        log(f"  map+file-cards: {len(described):,} of {n_files:,} files described "
            f"({d_secs / 60:.0f} min of model time); sections mapped on arrival")
        retrievers.append(chain)
    elif have_reader and not args.no_lazy:
        log(f"  map+file-cards: skipped, no file descriptions in {store.dir}. Build them with:\n"
            f"    python -m mapnet.cards {corpus} --store {store.dir} --files-only"
            + (f" --only {args.only}" if args.only else ""))
    # the full chain walked by meaning: embeds the map (files, sections), not the passages
    meaning = None
    if "map+meaning" not in skip_set:
        m_dir = data / "work" / "meaning-cards"  # section cards start empty every run
        if m_dir.exists():
            shutil.rmtree(m_dir)
        m_store = (CombinedCards(HideCards(store, held_texts), CardStore(m_dir)) if store.count_files()
                   else CardStore(m_dir))
        m_shared = Shared(work, cards=m_store)
        router = MeaningRouter(m_shared.map, emb)
        t0 = time.perf_counter()
        n_vec, _ = router.build(log)
        meaning_build = time.perf_counter() - t0
        meaning = MapLazy(m_shared, m_store, reader if (have_reader and not args.no_lazy) else None,
                          name="map+meaning", route_weight=0.3, router=router)
        log(f"  map+meaning: {n_vec:,} map vectors (vs {n_chunks:,} passages) in {meaning_build:.1f}s"
            f"{'; file descriptions' if store.count_files() else ''}"
            f"{'; sections mapped on arrival' if meaning.lazy else ''}")
        retrievers.append(meaning)
    retrievers.append(MapEmbed(shared, embed_all))

    # a network of tokens pointing at passages (no model); the second also follows word associations
    tnet = tassoc = None
    if "token-net" not in skip_set or "token-net+assoc" not in skip_set:
        tnet = TokenNetRoute(shared)
        log(f"  token-net: {len(tnet.net.vocab):,} tokens linked to {len(tnet.net.ids):,} passages "
            f"in {tnet.build_s:.1f}s (no model)")
        if "token-net" not in skip_set:
            retrievers.append(tnet)
        if "token-net+assoc" not in skip_set:
            tassoc = TokenNetRoute(shared, assoc=True, name="token-net+assoc", share=tnet)
            retrievers.append(tassoc)
        if "token-net+sections" not in skip_set:
            sec_route = next(r for r in retrievers if r.name == "map+sections")
            retrievers.append(TokenFusion(tnet, sec_route))

    # the token network with positions: proximity of the question's words, and the words beside them
    twin = None
    win_variants = (("token-prox", True, False, {}), ("token-window", False, True, {}),
                    ("token-prox+window", True, True, {}),
                    ("token-conv-window", False, True, dict(converge=2, link_n=20)))
    for name, prox, expand, skw in win_variants:
        if name in skip_set:
            continue
        twin = TokenWinRoute(shared, prox=prox, expand=expand, name=name, share=twin, search_kw=skw)
        if twin.build_s:
            log(f"  token positions: {len(twin.net.vocab):,} tokens, window {twin.net.window}, "
                f"built in {twin.build_s:.1f}s (no model)")
        retrievers.append(twin)

    # question words light up the words used in the same contexts (vectors from the embedding index)
    tgraph = None
    for name, prox, skw in (("token-graph", False, {}), ("token-graph+prox", True, {}),
                            ("token-conv-graph", False, dict(converge=2, link_n=20)),
                            ("token-conv-graph2", False, dict(converge=2, hops=2, link_n=20))):
        if name in skip_set:
            continue
        tgraph = TokenGraphRoute(shared, lambda ids: embed_all.M[[embed_all.index[d] for d in ids]],
                                 prox=prox, name=name, share=tgraph, search_kw=skw)
        if tgraph.build_s:
            log(f"  token-graph: word vectors from the embedding index's passage vectors; "
                f"{len(tgraph.net.vocab):,} words")
        retrievers.append(tgraph)

    # the map walked by meaning, files embedded on arrival, with its own empty cache
    etree = None
    if "embed-tree" not in skip_set:
        if isinstance(emb, OllamaEmbedder):
            t_dir = data / "work" / "tree-cache"  # empty every run: first visits are real work
            if t_dir.exists():
                shutil.rmtree(t_dir)
            t_emb = OllamaEmbedder(emb.model, cache_dir=str(t_dir))
        else:
            t_emb = emb  # stand-in embedder (no Ollama)
        t_store = HideCards(store, held_texts) if store.count_files() else None
        t0 = time.perf_counter()
        etree = EmbedTreeRoute(Shared(work, cards=t_store), t_emb)
        log(f"  embed-tree: {etree.tree.label_vectors:,} direction vectors (one per file) in "
            f"{time.perf_counter() - t0:.1f}s; file contents embedded only when the walk arrives")
        retrievers.append(etree)

    # the map of references: descriptions + questions, each placed where it resolves
    refmap = None
    if "ref-map" not in skip_set:
        if isinstance(emb, OllamaEmbedder):
            r_dir = data / "work" / "refmap-cache"  # empty every run: all embedding is counted
            if r_dir.exists():
                shutil.rmtree(r_dir)
            r_emb = OllamaEmbedder(emb.model, cache_dir=str(r_dir))
        else:
            r_emb = emb
        if not store.count_files():
            log("  ref-map: no file descriptions found, so its only references are paths and headings. "
                "Build descriptions first: python -m mapnet.cards ... --files-only")
        refmap = RefMapRoute(Shared(work, cards=HideCards(store, held_texts) if store.count_files() else None),
                             r_emb, log)
        log(f"  ref-map: {refmap.map.vectors:,} references ({refmap.map.placed_away:,} placed outside their "
            f"file's own folder) in {refmap.build_s:.0f}s; file contents embedded only on arrival")
        retrievers.append(refmap)
    # Variants of ref-map. Each reads the same references but has its OWN record of the files it
    # has read and its own empty embedding cache, so every variant pays its own first-visit cost.
    def fresh_embedder(tag):
        if not isinstance(emb, OllamaEmbedder):
            return emb
        d = data / "work" / f"{tag}-cache"
        if d.exists():
            shutil.rmtree(d)
        return OllamaEmbedder(emb.model, cache_dir=str(d))

    translator = TermTranslator(reader) if have_reader else None
    terms_route = graph_route = graph_terms_route = None
    if refmap is not None:
        if translator and "ref-map+terms" not in skip_set:
            terms_route = RefMapRoute(None, embedder=fresh_embedder("refmap-terms"), name="ref-map+terms",
                                      share=refmap, translator=translator)
            log("  ref-map+terms: same references; each question is first translated into technical terms "
                f"by {reader.model} (one short call per question, counted in its lookup time)")
            retrievers.append(terms_route)
        if "ref-graph" not in skip_set:
            graph_route = RefGraphRoute(refmap, fresh_embedder("refgraph"))
            st = graph_route.graph.stats()
            log(f"  ref-graph: the same references as a navigable graph: {st['nodes']:,} nodes, "
                f"{st['layers']} layers, {st['groups']} access group(s), built in {graph_route.build_s:.1f}s")
            retrievers.append(graph_route)
        if translator and graph_route is not None and "ref-graph+terms" not in skip_set:
            graph_terms_route = RefGraphRoute(refmap, fresh_embedder("refgraph-terms"), translator=translator,
                                              name="ref-graph+terms")
            retrievers.append(graph_terms_route)
    # page vectors: a file is represented by its own text, not by a model-written description
    page_routes = []
    for mode in ("mean", "text"):
        if f"page-{mode}" not in skip_set:
            pr = PageMapRoute(Shared(work), fresh_embedder(f"page-{mode}"), mode=mode)
            log(f"  page-{mode}: {len(pr.map.page):,} page vectors in {pr.build_s:.0f}s "
                f"({pr.map.passages_embedded:,} passages embedded up front)")
            page_routes.append(pr)
            retrievers.append(pr)
    # hybrids: the token network (words, model-free) merged with an embedding method by rank
    if tnet is not None:
        for other, name in (("page-mean", "token-net+page-mean"), ("embed-all", "token-net+embed-all")):
            route = next((r for r in retrievers if r.name == other), None)
            if route is not None and name not in skip_set:
                retrievers.append(TokenFusion(tnet, route, name=name))
    tg = next((r for r in retrievers if r.name == "token-graph"), None)
    pm0 = next((r for r in retrievers if r.name == "page-mean"), None)
    if tg is not None and pm0 is not None and "token-graph+page-mean" not in skip_set:
        retrievers.append(TokenFusion(tg, pm0, name="token-graph+page-mean"))
    pw = next((r for r in retrievers if r.name == "token-prox+window"), None)
    pm = next((r for r in retrievers if r.name == "page-mean"), None)
    if pw is not None and pm is not None and "token-prox+window+page-mean" not in skip_set:
        retrievers.append(TokenFusion(pw, pm, name="token-prox+window+page-mean"))
    skip = {x.strip() for x in args.skip.split(",") if x.strip()}
    retrievers = [r for r in retrievers if r.name not in skip]
    names = [r.name for r in retrievers]

    if args.generate:
        if have_reader:
            log(f"\nGenerating {args.generate} questions with {reader.model} ...")
            items += generate(shared, reader, args.generate, log=log)
        else:
            log("! --generate needs the reader model in Ollama; skipping.")
    judge_model = reader if have_reader else next((r for r in (answer_readers or []) if r.available()
                                                   and isinstance(r, OllamaReader)), None)
    model_judge = ModelJudge(judge_model) if judge_model else None

    # ---- phase A
    setup_s = time.perf_counter() - t_start
    timing = {}
    normal = [x for x in items if not x.get("fresh")]
    log(f"\nPhase A: {len(normal)} questions, one method at a time ...")
    t_a = time.perf_counter()
    rows = evaluate(normal, retrievers, args.k, answer_readers, args.answer_with.split(","), model_judge,
                    timing)
    phase_a_s = time.perf_counter() - t_a
    phase_b_s = 0.0

    # ---- optional: why did ref-map miss? (walk vs scoring every reference directly)
    explain_rows = []
    if args.explain and refmap is not None:
        log("\nExplaining ref-map ...")
        for item in normal:
            if item.get("generated"):
                continue
            ex = refmap.map.explain(item["q"], item["files"])
            ex["gold"] = item["files"]
            if terms_route is not None:
                et = refmap.map.explain(item["q"], item["files"], translator=terms_route.translator)
                ex["with_terms"] = {k: et[k] for k in ("flat_rank", "walk_rank", "in_chosen", "flat_top", "terms")}
            if graph_route is not None:
                g = graph_route.graph.explain(item["q"], item["files"])
                ex["graph"] = dict(in_chosen=g["in_chosen"], rank=g["rank"])
                if graph_terms_route is not None:
                    gt = graph_terms_route.graph.explain(item["q"], item["files"], translator=translator)
                    ex["graph"]["with_terms"] = dict(in_chosen=gt["in_chosen"], rank=gt["rank"])
            explain_rows.append(ex)

    # ---- phase B: freshness
    ingest = {}
    if fresh_items and held:
        t_b = time.perf_counter()
        log(f"\nPhase B: adding {len(held)} files that were held out, then asking about them ...")
        for f in held:
            (work / f).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(holdout_dir / f, work / f)
        t0 = time.perf_counter()
        shared.fm.sync()
        ingest["map + keyword index"] = time.perf_counter() - t0
        new = [(d, t) for d, t in shared.chunks() if d.split("#")[0] in set(held)]
        ingest["embedding index"] = embed_all.add(new)
        if tnet is not None:
            ingest["token-net (add the new files)"] = tnet.sync()
        if twin is not None:
            ingest["token positions (add the new files)"] = twin.sync()
        if tgraph is not None:
            ingest["token-graph (add the new files)"] = tgraph.sync()
        if lazy is not None:
            t0 = time.perf_counter()
            lazy.s.fm.sync()  # nothing to write now: new files get mapped when first visited
            ingest["map + lazy cards (mapped later, on first visit)"] = time.perf_counter() - t0
        if refmap is not None:
            t0 = time.perf_counter()
            refmap.s.fm.sync()
            if have_reader and store.count_files():  # the agent describes each new file on arrival...
                for f in held:
                    refmap.s.map.set_file_card(f, make_file_card(read_file(work / f), f, reader))
            refmap.map.build()  # ...and registers its references where they resolve
            ingest["ref-map (describe + register the new files)"] = time.perf_counter() - t0
        for pr in page_routes:
            t0 = time.perf_counter()
            pr.s.fm.sync()
            pr.map.sync()  # embeds the new files (page vector; passages too in mean mode)
            ingest[f"{pr.name} (embed the new files)"] = time.perf_counter() - t0
        if etree is not None:
            t0 = time.perf_counter()
            etree.s.fm.sync()
            etree.tree.build()  # one direction vector per new file; content on first visit
            ingest["embed-tree (direction vectors for the new files)"] = time.perf_counter() - t0
        if meaning is not None:
            t0 = time.perf_counter()
            meaning.s.fm.sync()
            if meaning.lazy and store.count_files():
                meaning.lazy.describe_now(held)
            meaning.router.build()  # embed the map entries of the new files
            ingest["map + meaning vectors for the new files"] = time.perf_counter() - t0
        if chain is not None:
            t0 = time.perf_counter()
            chain.s.fm.sync()
            chain.lazy.describe_now(held)  # new files get their one-line description on arrival
            ingest["map + file descriptions (written on arrival)"] = time.perf_counter() - t0
        if shared_cards is not None:
            t0 = time.perf_counter()
            shared_cards.fm.sync()
            if have_reader:  # new files get their cards written on arrival
                for f in held:
                    shared_cards.map.set_cards(f, make_cards(read_file(work / f), f, reader))
                ingest["map + cards (cards written by the model on arrival)"] = time.perf_counter() - t0
            else:
                ingest["map + cards (no model: new files have no cards)"] = time.perf_counter() - t0
        rows += evaluate(fresh_items, retrievers, args.k, answer_readers,
                         args.answer_with.split(","), model_judge, timing)
        phase_b_s = time.perf_counter() - t_b
    total_s = time.perf_counter() - t_start

    # ---- report
    out = HERE / "results" / datetime.now().strftime("%Y%m%d-%H%M%S")
    out.mkdir(parents=True, exist_ok=True)
    meta = dict(corpus=str(corpus), files=n_files, passages=n_chunks, k=args.k,
                reader=", ".join(r.model for r in answer_readers) if answer_readers else None,
                cartographer=reader.model if have_reader else None, embedder=emb.name,
                build_map_s=round(shared.build_s, 2), build_embed_s=round(embed_all.build_s, 2),
                ingest_s={k: round(v, 3) for k, v in ingest.items()})
    ret_t, ans_t = timing.get("retrieve", {}), timing.get("answer", {})
    time_lines = [f"- **Total wall-clock: {_dur(total_s)}.** Setup (indexes, embeddings, descriptions) "
                  f"{_dur(setup_s)}; phase A {_dur(phase_a_s)}"
                  + (f"; phase B {_dur(phase_b_s)}" if phase_b_s else "") + ".",
                  f"- Time retrieving (all methods): {_dur(sum(ret_t.values()))}"
                  + (" (" + ", ".join(f"{n} {_dur(v)}" for n, v in ret_t.items()) + ")" if ret_t else ""),
                  *([f"- Time answering: {_dur(sum(ans_t.values()))} ("
                     + ", ".join(f"{m} {_dur(v)}" for m, v in ans_t.items()) + ")"] if ans_t else []),
                  "- The 'Lookup' columns below time only the retrieval step per question. The reader's "
                  "answer time is listed separately, and 'Per question' adds the two."]
    meta["wall_clock_s"] = dict(total=round(total_s, 1), setup=round(setup_s, 1), phase_a=round(phase_a_s, 1),
                                phase_b=round(phase_b_s, 1),
                                retrieve={k: round(v, 1) for k, v in ret_t.items()},
                                answer={k: round(v, 1) for k, v in ans_t.items()})
    groups = {"Hand-written questions": [r for r in rows if not r["generated"] and not r["fresh"]],
              "Generated questions": [r for r in rows if r["generated"]],
              "Fresh files (added after indexing)": [r for r in rows if r["fresh"]]}
    md = [f"# MapNet real test — {datetime.now():%Y-%m-%d %H:%M}", "",
          f"- Corpus: `{corpus}` — {n_files:,} files, {n_chunks:,} passages",
          f"- Reader (answers): {meta['reader'] or 'none (retrieval only)'}; "
          f"cartographer (writes the map): {meta['cartographer'] or 'none'}; "
          f"navigator: words + {emb.name}; k = {args.k}",
          f"- Build time: map {meta['build_map_s']}s, embeddings {meta['build_embed_s']}s",
          *([f"- Cards: {card_info[0]:,} of {n_files:,} files carded, "
             f"{card_info[1] / 60:.0f} min of model time"] if card_info else []),
          *([f"- File descriptions: {file_info[0]:,} of {n_files:,} files, "
             f"{file_info[1] / 60:.0f} min of model time, built in advance"] if file_info else []),
          *([f"- map+file-cards: {chain.lazy.files} files mapped on first visit, "
             f"{chain.lazy.seconds / 60:.1f} min of model time"] if chain else []),
          *([f"- map+meaning: {meaning.router.vectors:,} map vectors embedded in total "
             f"(vs {n_chunks:,} passages for embed-all), {meaning.router.seconds:.0f}s"
             + (f"; {meaning.lazy.files} files mapped on first visit" if meaning.lazy else "")]
            if meaning else []),
          *([f"- ref-map: {refmap.map.vectors:,} references registered "
             f"({refmap.map.placed_away:,} outside their file's own folder); "
             f"{refmap.map.files_embedded} of {n_files} files embedded on arrival "
             f"({refmap.map.passages_embedded:,} passages); {refmap.map.embed_seconds:.0f}s of embedding in total"]
            if refmap else []),
          *([f"- ref-map+terms: {terms_route.translator.calls} questions translated, "
             f"{terms_route.translator.seconds:.0f}s of model time; same references as ref-map, but its own "
             f"record of the files it has read"]
            if terms_route else []),
          *([f"- ref-graph: {graph_route.graph.stats()['nodes']:,} references linked as a graph "
             f"({graph_route.graph.stats()['layers']} layers); {graph_route.map.files_embedded} files embedded "
             f"on arrival ({graph_route.map.passages_embedded:,} passages)"] if graph_route else []),
          *([f"- ref-map+terms and ref-graph+terms share one translator, so the translation time is "
             f"counted in whichever of them ran first"] if terms_route and graph_terms_route else []),
          *(f"- {pr.name}: {len(pr.map.page):,} page vectors; {pr.map.files_embedded} files and "
            f"{pr.map.passages_embedded:,} of {n_chunks:,} passages embedded, {pr.map.embed_seconds:.0f}s of "
            f"embedding in total" for pr in page_routes),
          *([f"- embed-tree: {etree.tree.files_embedded} of {n_files} files embedded on arrival "
             f"({etree.tree.passages_embedded:,} of {n_chunks:,} passages), "
             f"{etree.tree.embed_seconds:.0f}s of embedding in total"] if etree else []),
          *([f"- Lazy cards: {lazy.lazy.files} files mapped on first visit during the test, "
             f"{lazy.lazy.seconds / 60:.1f} min of model time "
             f"({lazy.lazy.seconds / max(lazy.lazy.files, 1):.0f} s per first visit, included in "
             f"map+lazy-cards lookup times)"] if lazy else []),
          *(f"- Absorbing {len(held)} new files: {k} {v * 1000:.0f} ms" for k, v in ingest.items()),
          *time_lines,
          ""]
    summaries = {}
    for title, rs in groups.items():
        if rs:
            summaries[title] = summarize(rs, names)
            md.append(table(summaries[title], title))
            if answer_readers:
                md.append(time_table(summaries[title], title))
    if any(r["generated"] for r in rows):
        md.append("_Generated questions often reuse the source passage's wording, which favours "
                  "keyword search. Weigh the hand-written results more._\n")
    explain_md = explain_report(explain_rows, refmap.map.file_beam if refmap else 6)
    if explain_md:
        md.append(explain_md)
    md.append("## Misses (hand-written questions)\n")
    for name in names:
        miss = [r for r in rows if r["retriever"] == name and not r["found"] and not r["generated"]]
        md.append(f"**{name}** ({len(miss)}): " + "; ".join(f"“{r['q']}” → {r['files'][:2]}" for r in miss)
                  + "\n" if miss else f"**{name}**: none\n")
    (out / "results.json").write_text(json.dumps(dict(meta=meta, summaries=summaries, rows=rows,
                                                      explain=explain_rows), indent=1, default=str),
                                      encoding="utf-8")
    (out / "report.md").write_text("\n".join(md), encoding="utf-8")
    log("\n" + "\n".join(md[: 6 + len(ingest) + len(time_lines) + (1 if card_info else 0) + (1 if lazy else 0)
                            + (2 if chain else 0) + (1 if meaning else 0) + (1 if etree else 0)
                            + (1 if refmap else 0) + (1 if terms_route else 0) + (1 if graph_route else 0)
                            + (1 if terms_route and graph_terms_route else 0)]))
    for title, s in summaries.items():
        log(table(s, title))
        if answer_readers:
            log(time_table(s, title))
    if explain_md:
        log(explain_md)
    log(f"Full report: {out / 'report.md'}")


if __name__ == "__main__":
    main()
